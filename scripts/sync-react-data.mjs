import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

async function generateNtc() {
  const source = await readFile(path.join(root, "inkscape", "hueprint_ntc.js"), "utf8");
  const entries = [...source.matchAll(/\["([0-9A-Fa-f]{6})",\s*"((?:[^"\\]|\\.)*)"\]/g)].map((match) => [match[1].toUpperCase(), JSON.parse(`"${match[2]}"`)]);
  if (entries.length < 1500) throw new Error(`Expected the complete NTC library; found ${entries.length} entries.`);
  const output = `// Generated by scripts/sync-react-data.mjs from inkscape/hueprint_ntc.js.\nexport const ntcNames = ${JSON.stringify(entries)} as const;\n`;
  await writeFile(path.join(root, "src", "color-harmony-picker", "ntcNames.generated.ts"), output);
}

async function generateRecipeMetadata() {
  const source = await readFile(path.join(root, "inkscape", "hueprint_recipe_metadata.py"), "utf8");
  const entries = [...source.matchAll(/RecipeMetadata\("((?:[^"\\]|\\.)*)",\s*"((?:[^"\\]|\\.)*)",\s*"((?:[^"\\]|\\.)*)",\s*"((?:[^"\\]|\\.)*)",\s*"((?:[^"\\]|\\.)*)",\s*"((?:[^"\\]|\\.)*)"\)/g)].map((match) => ({
    id: JSON.parse(`"${match[1]}"`),
    currentName: JSON.parse(`"${match[2]}"`),
    displayName: JSON.parse(`"${match[3]}"`),
    category: JSON.parse(`"${match[4]}"`),
    character: JSON.parse(`"${match[5]}"`),
    description: JSON.parse(`"${match[6]}"`),
  }));
  if (entries.length !== 71) throw new Error(`Expected 71 recipe metadata entries; found ${entries.length}.`);
  const output = `// Generated by scripts/sync-react-data.mjs from inkscape/hueprint_recipe_metadata.py.\nexport const recipeMetadata = ${JSON.stringify(entries, null, 2)} as const;\n`;
  await writeFile(path.join(root, "src", "color-harmony-picker", "recipeMetadata.generated.ts"), output);
}

await Promise.all([generateNtc(), generateRecipeMetadata()]);
